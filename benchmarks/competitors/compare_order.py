"""Published procedures beside the lineage share of the MIC ordering, on the same datasets.

Every replicate of a design is generated by the generator of
``benchmarks/order_calibration.py`` from its seed, at replicate indices from
CONFIRMATORY_OFFSET on, so that no dataset of that study recurs here, and is
passed to ``compare_order.R``, which runs the seven published procedures
listed there; the lineage share and its test are computed here on the same
datasets, within laboratories where there are two. The designs are the
designs of the ordering-share study without a lineage effect and with a
weak one, where the procedures differ, and four more:

``weak_two_labs``   ``two_labs`` with 10 % of the latent variance between lineages;
``weak_spread``     10 %, two laboratories on one panel that differ in spread
                    (standard deviations 0.6 and 1.8), 85 % of a lineage's
                    readings in its home laboratory;
``weak_t4``         10 %, one laboratory, residuals t with 4 degrees of freedom;
``weak_wt_nwt``     ``wt_nwt`` with 10 % of the liability to the upper mode
                    between lineages;
``null_small``, ``weak_small``   100 lineages of three isolates, no effect or 10 %;
``null_offset_spread``, ``weak_offset_spread``   two laboratories that differ
                    in offset and in spread, 85 % of a lineage in one of them.

The hypotheses and decision rules are those of
``benchmarks/CONFIRMATORY_PROTOCOL.md`` (Study 4), fixed before the run.

Usage::

    python compare_order.py --design NAME --start 0 --replicates 250 --output DIR/chunk.csv
    python compare_order.py --summarize DIR --output SUMMARY_DIR
"""
from __future__ import annotations

import argparse
import json
import subprocess
import tempfile
from pathlib import Path

import numpy as np
import pandas as pd

from amr_clonalshare.mic_order import mic_order_share
from benchmarks.order_calibration import NARROW, ROOT_SEED, WIDE, _design, generate, order_design_grid

HERE = Path(__file__).resolve().parent
PROCEDURES = ("anova", "lmm", "cens", "kw", "ricc", "ict", "strat")
#: "null" names a design, not a missing value; R writes a failed fit as NA
NA = dict(keep_default_na=False, na_values=["", "NA"])


def added_designs():
    two = ((-.5, WIDE, 1.), (.5, NARROW, 1.))
    grid = [
        _design("weak_two_labs", rho=.1, labs=two, alignment=.85, replicates=1000),
        _design("weak_spread", rho=.1, labs=((0., WIDE, .6), (0., WIDE, 1.8)), alignment=.85, replicates=1000),
        _design("weak_t4", rho=.1, residual="t4", replicates=1000),
        _design("weak_wt_nwt", rho=.1, sizes="ssuis", residual="wt_nwt", replicates=1000),
    ]
    for k, cell in enumerate(grid):
        cell["cell"] = 100 + k
    return grid


#: The replicates are drawn from this index on, so that no dataset of the
#: ordering-share study recurs here.
CONFIRMATORY_OFFSET = 2_000_000
#: The designs of the ordering-share study repeated here.
CONFIRMATORY_TABLE = ("null", "null_lab_offset_85", "null_lab_offset_100", "null_lab_panel_100",
                      "null_lab_spread_85", "null_lab_few_100", "gauss_0.1", "few", "weak_two_labs",
                      "weak_spread", "weak_t4", "weak_wt_nwt")


def confirmatory_designs():
    spread = ((-.5, WIDE, .6), (.5, WIDE, 1.8))
    new = [_design("null_small", rho=0., groups=100, sizes="three", replicates=5000),
           _design("weak_small", rho=.1, groups=100, sizes="three", replicates=2000),
           _design("null_offset_spread", rho=0., labs=spread, alignment=.85, replicates=5000),
           _design("weak_offset_spread", rho=.1, labs=spread, alignment=.85, replicates=2000)]
    for k, cell in enumerate(new):
        cell["cell"] = 104 + k
    table = [dict(c, replicates=5000 if c["rho"] == 0. else 2000)
             for c in order_design_grid() + added_designs() if c["design"] in CONFIRMATORY_TABLE]
    return {c["design"]: c for c in table + new}


def run_chunk(name, start, replicates, output: Path):
    cell = confirmatory_designs()[name]
    frames, ours = [], []
    for rep in range(start + CONFIRMATORY_OFFSET, start + CONFIRMATORY_OFFSET + replicates):
        data = generate(cell, rep)
        frames.append(pd.DataFrame(dict(design=name, replicate=rep, lo=data["lo"], hi=data["hi"],
                                        lineage=data["lineage"], lab=data["lab"])))
        row = dict(design=name, replicate=rep, n_all=int(data["lineage"].size))
        strata = data["lab"] if len(cell["labs"]) > 1 else None
        seed = int(np.random.SeedSequence([ROOT_SEED, cell["cell"], rep, 7]).generate_state(1)[0])
        r = mic_order_share(data["lo"], data["hi"], data["lineage"], strata=strata,
                            stratified_by="laboratory" if strata is not None else None, n_boot=0, seed=seed)
        row.update(estimate=r["kappa_adj"], p_value=r["p_value"])
        ours.append(row)
    with tempfile.TemporaryDirectory() as tmp:
        readings, results = Path(tmp) / "readings.csv", Path(tmp) / "results.csv"
        pd.concat(frames).to_csv(readings, index=False)
        subprocess.run(["Rscript", str(HERE / "compare_order.R"), str(readings), str(results)], check=True)
        other = pd.read_csv(results, **NA)
    output.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(ours).merge(other, on=["design", "replicate"], how="outer").to_csv(output, index=False)


def _wilson(k, n, z=1.959963984540054):
    if n == 0:
        return float("nan"), float("nan")
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return float(centre - half), float(centre + half)


def summarize(chunks: Path, out: Path):
    """Rejection rates, paired differences and the verdicts of the protocol.

    H1: in every design without a lineage effect the test of the ordering
    share meets the level rule (lower Wilson 95% limit of its rejection rate
    at most 0.05). H2: in every design with one, its rejection rate is not
    below that of the stratified Wilcoxon test by more than one percentage
    point (lower limit of the two-sided 95% interval of the paired difference
    at least -0.01). The paired differences against every other procedure are
    reported whichever way they fall."""
    d = pd.concat([pd.read_csv(p, **NA) for p in sorted(chunks.glob("*.csv"))], ignore_index=True)
    grid = confirmatory_designs()
    rows, paired, verdict = [], [], dict(level={}, noninferior_to_stratified={})
    for name, cell in grid.items():
        g = d[d.design == name]
        if len(g) != cell["replicates"] or g.replicate.duplicated().any():
            raise SystemExit(f"confirmatory design {name}: {len(g)} of {cell['replicates']} replicates")
        for col in ["p_value"] + [f"{k}_p" for k in PROCEDURES]:
            p = g[col]
            ok = p.notna()
            k = int((p[ok] <= .05).sum())
            low, high = _wilson(k, int(ok.sum()))
            rows.append(dict(design=name, rho=cell["rho"], procedure=col, replicates=int(ok.sum()),
                             failed=int((~ok).sum()), rejection=k / max(int(ok.sum()), 1),
                             wilson_low=low, wilson_high=high))
        if cell["rho"] == 0.:
            k = int((g.p_value <= .05).sum())
            verdict["level"][name] = bool(_wilson(k, len(g))[0] <= .05)
        else:
            ours = (g.p_value <= .05).to_numpy(float)
            for col in [f"{k}_p" for k in PROCEDURES]:
                ok = g[col].notna().to_numpy()
                diff = ours[ok] - (g[col][ok] <= .05).to_numpy(float)
                se = float(diff.std(ddof=1) / np.sqrt(diff.size)) if diff.size > 1 else float("nan")
                paired.append(dict(design=name, procedure=col, difference=float(diff.mean()), se=se,
                                   low=float(diff.mean() - 1.96 * se), high=float(diff.mean() + 1.96 * se)))
                if col == "strat_p":
                    verdict["noninferior_to_stratified"][name] = bool(diff.mean() - 1.96 * se >= -.01)
    verdict["H1_level_in_every_null_design"] = all(verdict["level"].values())
    verdict["H2_noninferior_in_every_effect_design"] = all(verdict["noninferior_to_stratified"].values())
    out.mkdir(parents=True, exist_ok=True)
    d.sort_values(["design", "replicate"]).to_csv(out / "confirmatory_replicates.csv.gz", index=False)
    pd.DataFrame(rows).to_csv(out / "confirmatory_rejection.csv", index=False)
    pd.DataFrame(paired).to_csv(out / "confirmatory_paired.csv", index=False)
    (out / "confirmatory_verdict.json").write_text(json.dumps(verdict, indent=1) + "\n")
    print(json.dumps(verdict, indent=1))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--design")
    parser.add_argument("--start", type=int, default=0)
    parser.add_argument("--replicates", type=int, default=10)
    parser.add_argument("--summarize", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.summarize is not None:
        summarize(args.summarize, args.output)
        return
    names = confirmatory_designs()
    if args.design not in names or args.start < 0 or args.replicates < 1:
        parser.error("invalid design or replicates")
    if args.output.exists():
        raise FileExistsError(args.output)
    run_chunk(args.design, args.start, args.replicates, args.output)


if __name__ == "__main__":
    main()
